CREATE TABLE GLOBAL_TB_REFRESH_TOKEN (
  ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  IDENTITY_ID   NUMBER NOT NULL,
  TOKEN_ID      VARCHAR2(36) NOT NULL,
  PLATFORM_CODE VARCHAR2(50),
  EXPIRES_AT    TIMESTAMP NOT NULL,
  REVOKED       NUMBER(1) DEFAULT 0 NOT NULL,
  CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_REFRESH_TOKEN_IDENTITY FOREIGN KEY (IDENTITY_ID)
    REFERENCES GLOBAL_TB_IDENTITY (ID),
  CONSTRAINT UQ_REFRESH_TOKEN_TOKEN_ID UNIQUE (TOKEN_ID)
);

CREATE INDEX IDX_REFRESH_TOKEN_IDENTITY ON GLOBAL_TB_REFRESH_TOKEN (IDENTITY_ID);
